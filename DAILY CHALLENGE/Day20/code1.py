import numpy as np

a = np.array([1,2,3])
b = np.array([[10],
              [20],
              [30]])

print(a + b)

'''
    <-- Addition -->
      [1  2  3]
10 + [1  2  3] = [11 12 13]

20 + [1  2  3] = [21 22 23]

30 + [1  2  3] = [31 32 33]

    <-- Result -->
    [[11 12 13]
    [21 22 23]
    [31 32 33]]
'''